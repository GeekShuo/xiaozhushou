def normalize(text: str) -> str:
    t = text.lower()
    rules = {
        "减肥": ["减肥", "瘦", "weight", "fat", "身材", "塑形"],
        "赚钱": ["赚钱", "搞钱", "财富", "收入", "副业", "money", "富", "挣"],
        "学ai编程": ["ai编程", "人工智能编程", "学编程", "写代码", "python", "学ai", "大模型", "llm"],
        "英语口语": ["英语", "口语", "english", "雅思", "托福", "spoken"],
        "表达力": ["表达", "演讲", "沟通", "口才", "表达力", "说话", "社交", "泡妞", "恋爱", "人际"],
    }
    for key, kws in rules.items():
        if any(k in t for k in kws):
            return key
    return "generic"


def _p(title, weeks, rationale, tasks):
    return Phase(title=title, weeks=weeks, rationale=rationale,
                 tasks=[Task(id="", title=t[0], detail=t[1],
                             frequency=t[2], duration_min=t[3]) for t in tasks])


